export const getAllProducts = () => PRODUCTS

export const getProductBySlug = (slug) => PRODUCTS.find((p) => p.slug === slug)

export const getProductById = (id) => PRODUCTS.find((p) => p.id === id)

export const getFeaturedProducts = (limit = 8) =>
  PRODUCTS.filter((p) => p.featured).sort((a, b) => b.popularity - a.popularity).slice(0, limit)

export const getNewArrivals = (limit = 8) =>
  PRODUCTS.filter((p) => p.newArrival)
    .sort((a, b) => new Date(b.dateAdded) - new Date(a.dateAdded))
    .slice(0, limit)

export const getRelatedProducts = (product, limit = 4) => {
  const sameCategory = PRODUCTS.filter((p) => p.id !== product.id && p.category === product.category)
  const others = PRODUCTS.filter((p) => p.id !== product.id && p.category !== product.category && p.featured)
  return [...sameCategory, ...others].slice(0, limit)
}

export const isInStock = (product) => product.stock > 0
